interface MarkerText {
  meaning: string;
  feeling?: string;
  commentary?: string;
  nameOverride?: string;
}

function m(code: string, value: number, text: MarkerText): ExampleMarker {
  const ref = REF[code];
  if (!ref) throw new Error(`Нет референса для биомаркера ${code}`);
  return {
    code,
    name: text.nameOverride || ref.name,
    unit: ref.unit,
    value,
    biomarker: { ...ref },
    meaning: text.meaning,
    feeling: text.feeling,
    commentary: text.commentary,
  };
}

